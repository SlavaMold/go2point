TripRoute _trip({
  required int id,
  required String city,
  required String country,
  required DateTime arrival,
  required DateTime departure,
  required String event,
  required String venue,
  required DateTime eventDate,
  required TripRouteCategory category,
  required String title,
  required String travelTime,
  required String transportChain,
  required String transfers,
  required String hotel,
  required String hotelInfo,
  required List<double> prices,
  bool byTrain = false,
  bool isRecommended = false,
}) {
  final terminal = '$city ${byTrain ? 'Station' : 'Airport'}';
  return TripRoute(
    id: id,
    city: city,
    country: country,
    arrivalDate: arrival,
    departureDate: departure,
    eventDate: eventDate,
    category: category,
    title: title,
    travelTime: travelTime,
    transportChain: transportChain,
    transfers: transfers,
    hotelInfo: hotelInfo,
    isRecommended: isRecommended,
    steps: [
      TripStep(
        kind: byTrain ? TripStepKind.train : TripStepKind.flight,
        title: byTrain ? 'Train journey' : 'Flight',
        from: 'Chisinau',
        to: city,
        price: prices[0],
      ),
      TripStep(
        kind: TripStepKind.transfer,
        title: byTrain ? 'Station transfer' : 'Airport transfer',
        from: terminal,
        to: 'City center',
        price: prices[1],
      ),
      TripStep(
        kind: TripStepKind.hotel,
        title: 'Hotel',
        from: hotel,
        to: hotelInfo,
        price: prices[2],
      ),
      TripStep(
        kind: TripStepKind.event,
        title: 'Event ticket',
        from: event,
        to: venue,
        price: prices[3],
      ),
      TripStep(
        kind: TripStepKind.localTransport,
        title: 'Local transport',
        from: hotel,
        to: venue,
        price: prices[4],
      ),
      TripStep(
        kind: TripStepKind.returnTransfer,
        title: byTrain ? 'Return to station' : 'Return to airport',
        from: 'City center',
        to: terminal,
        price: prices[5],
      ),
    ],
  );
}
